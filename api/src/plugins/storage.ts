import fp from 'fastify-plugin';
import { randomBytes } from 'node:crypto';
import { constants } from 'node:fs';
import { access, mkdir, open, writeFile } from 'node:fs/promises';
import path from 'node:path';

type UploadTarget = 'avatar' | 'cover' | 'gallery';

export type StoredAsset = {
  key: string;
  url: string;
  contentType: string;
  size: number;
};

type StorageService = {
  checkConnection: () => Promise<void>;
  putImage: (input: {
    userId: string;
    target: UploadTarget;
    filename: string;
    contentType: string;
    buffer: Buffer;
  }) => Promise<StoredAsset>;
  getObject: (key: string) => Promise<{
    stream: NodeJS.ReadableStream;
    contentType: string;
    size: number;
  }>;
  buildPublicUrl: (key: string) => string;
};

declare module 'fastify' {
  interface FastifyInstance {
    storage: StorageService;
  }
}

function getFileExtension(contentType: string) {
  if (contentType === 'image/png') {
    return 'png';
  }

  if (contentType === 'image/webp') {
    return 'webp';
  }

  return 'jpg';
}

function buildObjectKey(userId: string, target: UploadTarget, contentType: string) {
  const extension = getFileExtension(contentType);
  const random = randomBytes(8).toString('hex');

  return `${userId}-${target}-${Date.now()}-${random}.${extension}`;
}

export default fp(async (fastify) => {
  const directory = path.resolve(process.env.UPLOADS_DIR ?? './uploads');
  await mkdir(directory, { recursive: true, mode: 0o700 });

  function objectPath(key: string) {
    // Stored keys are generated by this service, never paths supplied by clients.
    if (!/^[a-zA-Z0-9][a-zA-Z0-9._-]{0,500}\.(png|jpg|webp)$/.test(key)) {
      throw new Error('Invalid stored image key');
    }
    return path.join(directory, key);
  }

  const storage: StorageService = {
    async checkConnection() {
      await access(directory, constants.R_OK | constants.W_OK | constants.X_OK);
    },
    buildPublicUrl(key) {
      return `/api/backend/uploads/${encodeURIComponent(key)}`;
    },
    async putImage({ userId, target, contentType, buffer }) {
      const key = buildObjectKey(userId, target, contentType);
      // Exclusive creation preserves immutable URLs and prevents overwriting files.
      await writeFile(objectPath(key), buffer, { flag: 'wx', mode: 0o600 });

      return {
        key,
        url: storage.buildPublicUrl(key),
        contentType,
        size: buffer.length,
      };
    },
    async getObject(key) {
      // Refuse symlinks even if a file was placed in the volume outside the API.
      const handle = await open(objectPath(key), constants.O_RDONLY | constants.O_NOFOLLOW);
      try {
        const stat = await handle.stat();
        if (!stat.isFile()) throw new Error('Stored object is not a file');
        return {
          stream: handle.createReadStream({ autoClose: true }),
          contentType: key.endsWith('.png') ? 'image/png' : key.endsWith('.webp') ? 'image/webp' : 'image/jpeg',
          size: stat.size,
        };
      } catch (error) {
        await handle.close();
        throw error;
      }
    },
  };

  fastify.decorate('storage', storage);
});
